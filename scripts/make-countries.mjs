// Regenerates src/modules/countries/countryData.ts from the `world-countries` dev dependency.
// Run: node scripts/make-countries.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const all = require('world-countries');

const continent = (c) => {
  if (c.region === 'Americas') return c.subregion === 'South America' ? 'South America' : 'North America';
  if (c.region === 'Antarctic') return 'Antarctica';
  return c.region;
};

const rows = all
  .map((c) => [
    c.cca2,
    c.name.common,
    continent(c),
    c.ccn3 || '',
    Math.round((c.latlng?.[0] ?? 0) * 10) / 10,
    Math.round((c.latlng?.[1] ?? 0) * 10) / 10,
    c.independent ? 1 : 0,
    // Other names people (and Swarm) use for it.
    [...new Set([c.name.official, ...(c.altSpellings ?? []).filter((s) => s.length > 2)])].filter((s) => s !== c.name.common),
  ])
  .sort((a, b) => a[1].localeCompare(b[1]));

const out = `// Generated by scripts/make-countries.mjs from the world-countries package. Don't edit by hand.
// [ISO alpha-2, name, continent, ISO numeric (as in the map), lat, lng, independent (1/0), other names]
export type CountryRow = [string, string, string, string, number, number, 0 | 1, string[]];

export const COUNTRY_ROWS: CountryRow[] = ${JSON.stringify(rows)};
`;
writeFileSync(new URL('../src/modules/countries/countryData.ts', import.meta.url), out);
console.log(rows.length, 'countries');
